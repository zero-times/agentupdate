import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, readdir, rm, stat, symlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const options = process.argv.slice(2);
const candidate = !options.includes('--signed');
if (options.some(argument => !['--candidate', '--signed'].includes(argument)) || (options.includes('--candidate') && options.includes('--signed'))) throw new Error('Use --candidate (default) or --signed.');
if (process.platform !== 'darwin') throw new Error('macOS packaging requires a Mac.');
const config = JSON.parse(await readFile(path.join(repo, 'src-tauri/tauri.conf.json'), 'utf8'));
const version = config.version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error('A stable MAJOR.MINOR.PATCH version is required.');
const product = config.productName;
const targetRoot = path.resolve(repo, process.env.CARGO_TARGET_DIR || 'src-tauri/target');
const bundle = path.join(targetRoot, 'universal-apple-darwin/release/bundle/macos', product + '.app');
const runId = (candidate ? 'candidate-' : 'signed-') + new Date().toISOString().replace(/[-:.]/g, '');
const output = path.join(repo, 'release-artifacts', 'v' + version, runId);
const archiveName = product + '-' + version + '-macos-universal.app.zip';
const diskName = product + '-' + version + '-macos-universal.dmg';
const releaseUrl = 'https://github.com/zero-times/agentupdate/releases/tag/v' + version;
const profile = process.env.AGENTUPDATE_NOTARY_PROFILE;
const identity = process.env.AGENTUPDATE_SIGNING_IDENTITY;

function run(executable, args, stream = false, timeout = 60 * 60 * 1000) {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, { cwd: repo, stdio: ['ignore', 'pipe', 'pipe'] });
    let stdout = '', stderr = '';
    child.stdout.on('data', chunk => { stdout += chunk; if (stream) process.stdout.write(chunk); });
    child.stderr.on('data', chunk => { stderr += chunk; if (stream) process.stderr.write(chunk); });
    const timer = setTimeout(() => { child.kill('SIGKILL'); }, timeout);
    child.on('error', error => { clearTimeout(timer); reject(error); });
    child.on('close', code => {
      clearTimeout(timer);
      if (code === 0) resolve({ stdout: stdout.trim(), stderr: stderr.trim() });
      else reject(new Error(path.basename(executable) + ' exited ' + code + ': ' + (stderr.slice(-3000) || stdout.slice(-3000))));
    });
  });
}

function digest(bytes) { return createHash('sha256').update(bytes).digest('hex'); }
async function writeJson(file, value) { await writeFile(file, JSON.stringify(value, null, 2) + '\n'); }
async function sourceSnapshot() {
  const files = (await run('git', ['ls-files', '--cached', '--others', '--exclude-standard'])).stdout.split('\n').filter(file =>
    /^(src\/|src-tauri\/|scripts\/|\.cargo\/|package(?:-lock)?\.json$|rust-toolchain\.toml$|index\.html$|vite\.config\.ts$|tsconfig\.json$)/.test(file)
    && !/^(src-tauri\/(gen|permissions\/autogenerated)\/)/.test(file));
  const entries = [];
  for (const file of [...new Set(files)].sort()) entries.push({ path: file, sha256: digest(await readFile(path.join(repo, file))) });
  return { sha256: digest(JSON.stringify(entries)), files: entries };
}

const packageInfo = JSON.parse(await readFile(path.join(repo, 'package.json'), 'utf8'));
const lock = JSON.parse(await readFile(path.join(repo, 'package-lock.json'), 'utf8'));
const cargo = await readFile(path.join(repo, 'src-tauri/Cargo.toml'), 'utf8');
if ([packageInfo.version, lock.version, lock.packages[''].version, /^version = "([^"]+)"/m.exec(cargo)?.[1]].some(value => value !== version)) {
  throw new Error('package.json, package-lock.json, Cargo.toml and Tauri versions must match.');
}
const identities = (await run('/usr/bin/security', ['find-identity', '-v', '-p', 'codesigning'])).stdout;
if (!candidate) {
  if (!identity?.startsWith('Developer ID Application:') || !identities.includes('"' + identity + '"')) {
    throw new Error('Set AGENTUPDATE_SIGNING_IDENTITY to an installed Developer ID Application identity, or use --candidate for local review.');
  }
  if (!profile) throw new Error('AGENTUPDATE_NOTARY_PROFILE is required for signed packaging.');
  await run('/usr/bin/xcrun', ['notarytool', 'history', '--keychain-profile', profile, '--output-format', 'json'], false, 60_000);
}
await mkdir(path.join(repo, '.validation'), { recursive: true });
const staging = await mkdtemp(path.join(repo, '.validation/release-stage-'));
await mkdir(output, { recursive: true });
const manifest = {
  schemaVersion: 1, product, version, tag: 'v' + version, releaseUrl,
  runId, status: 'building', distributionReady: false, publicReleaseCreated: false,
  deliveryPolicy: candidate ? 'unsigned-local-use-accepted-by-user' : 'developer-id',
  signing: { kind: candidate ? 'ad-hoc' : 'Developer ID Application', verified: false },
  notarization: { app: { submitted: false }, diskImage: { submitted: false } },
  blockers: candidate ? ['Developer ID signing and Apple notarization are not completed.'] : [],
  acceptance: { cleanMacOS15: 'pending', physicalIntel: 'pending', packagedToolRoundtrip: 'pending' },
  checkedAt: new Date().toISOString(), artifacts: [],
};

async function notarize(file, key) {
  manifest.notarization[key].submitted = true;
  const result = JSON.parse((await run('/usr/bin/xcrun', ['notarytool', 'submit', file, '--keychain-profile', profile, '--wait', '--output-format', 'json'])).stdout);
  manifest.notarization[key] = { submitted: true, id: result.id, status: result.status };
  await writeJson(path.join(output, 'notarization-' + key + '.json'), result);
  if (result.status !== 'Accepted') throw new Error('Apple notarization rejected ' + key + '; inspect the submission log for ' + result.id + '.');
}

try {
  const snapshot = await sourceSnapshot();
  await writeJson(path.join(output, 'source-manifest.json'), snapshot);
  manifest.sourceSha256 = snapshot.sha256;
  try { manifest.sourceCommit = (await run('git', ['rev-parse', '--verify', 'HEAD'])).stdout; }
  catch { manifest.sourceCommit = null; }
  manifest.sourceDirty = Boolean((await run('git', ['status', '--porcelain'])).stdout);
  if (!manifest.sourceCommit || manifest.sourceDirty) manifest.blockers.push('Source must be committed and rebuilt from a clean release checkout before distribution.');
  const override = JSON.stringify({ bundle: { macOS: { signingIdentity: candidate ? '-' : identity, hardenedRuntime: true } } });
  await run('npm', ['run', 'tauri', '--', 'build', '--target', 'universal-apple-darwin', '--bundles', 'app', '--config', override, '--', '--locked'], true);
  if ((await sourceSnapshot()).sha256 !== snapshot.sha256) throw new Error('Source changed during the build; rerun packaging.');
  const app = path.join(staging, product + '.app');
  await run('/usr/bin/ditto', [bundle, app]);
  const binary = path.join(app, 'Contents/MacOS/agentupdate');
  const plist = path.join(app, 'Contents/Info.plist');
  const slices = (await run('/usr/bin/lipo', ['-archs', binary])).stdout.split(/\s+/).sort();
  if (slices.join(',') !== 'arm64,x86_64') throw new Error('Both macOS architectures are required.');
  for (const [key, expected] of [['CFBundleShortVersionString', version], ['CFBundleIdentifier', config.identifier], ['LSMinimumSystemVersion', '15.0']]) {
    if ((await run('/usr/bin/plutil', ['-extract', key, 'raw', plist])).stdout !== expected) throw new Error('Bundle ' + key + ' does not match ' + expected + '.');
  }
  const markers = (await run('/usr/bin/strings', [binary])).stdout;
  for (const forbidden of ['probe_panel', 'finish_panel_validation', 'AGENTUPDATE_VALIDATION_PANEL', 'finish_cli_launch_validation', 'AGENTUPDATE_TEST_DISCOVERY_DIR', 'AGENTUPDATE_VALIDATION_CLI_LAUNCH', 'finish_workflow_validation', 'finish_desktop_validation', 'restricted_probe', 'AGENTUPDATE_TEST_FAIL_SWAP_AGENT', 'AGENTUPDATE_TEST_FAIL_VERIFY_AGENT', 'AGENTUPDATE_TEST_FAIL_RESTORE_AGENT', 'AGENTUPDATE_TEST_CATALOG_DIR', 'AGENTUPDATE_TEST_OFFLINE', 'AGENTUPDATE_VALIDATION_WORKFLOW']) {
    if (markers.includes(forbidden)) throw new Error('Validation marker in production bundle: ' + forbidden);
  }
  for (const required of ['open_cli', 'save_cli_project', 'get_cli_projects', 'create_update_plan', 'check_app_release', 'rollback_update', 'check_desktop_apps', 'open_desktop_app_channel']) {
    if (!markers.includes(required)) throw new Error('Production command missing: ' + required);
  }
  if ((await readdir(path.join(repo, 'dist/assets'))).some(name => name.includes('validation'))) throw new Error('Validation frontend in production assets.');
  await run('/usr/bin/codesign', ['--verify', '--deep', '--strict', app]);
  const details = (await run('/usr/bin/codesign', ['-dv', '--verbose=4', app])).stderr;
  await writeFile(path.join(output, 'signature-app.txt'), details + '\n');
  if (candidate ? !details.includes('Signature=adhoc') : !details.includes('Authority=' + identity) || !details.includes('runtime') || !details.includes('Timestamp=')) throw new Error('Signing identity, runtime or timestamp verification failed.');
  manifest.architectures = slices;
  manifest.minimumSystemVersion = '15.0';
  manifest.binarySha256 = digest(await readFile(binary));
  manifest.productionCommandsVerified = true;
  manifest.validationMarkersAbsent = true;
  manifest.signing.verified = true;
  const archive = path.join(output, archiveName);
  await run('/usr/bin/ditto', ['-c', '-k', '--sequesterRsrc', '--keepParent', app, archive]);
  if (!candidate) {
    await notarize(archive, 'app');
    await run('/usr/bin/xcrun', ['stapler', 'staple', app]);
    await run('/usr/bin/xcrun', ['stapler', 'validate', app]);
    await run('/usr/sbin/spctl', ['--assess', '--type', 'execute', '--verbose=4', app]);
    manifest.notarization.app.stapled = true;
    await rm(archive);
    await run('/usr/bin/ditto', ['-c', '-k', '--sequesterRsrc', '--keepParent', app, archive]);
  }
  await symlink('/Applications', path.join(staging, 'Applications'));
  const disk = path.join(output, diskName);
  await run('/usr/bin/hdiutil', ['create', '-volname', product, '-srcfolder', staging, '-format', 'UDZO', disk]);
  if (!candidate) {
    await run('/usr/bin/codesign', ['--sign', identity, '--timestamp', disk]);
    await notarize(disk, 'diskImage');
    await run('/usr/bin/xcrun', ['stapler', 'staple', disk]);
    await run('/usr/bin/xcrun', ['stapler', 'validate', disk]);
    await run('/usr/bin/codesign', ['--verify', '--strict', disk]);
    await run('/usr/sbin/spctl', ['--assess', '--type', 'open', '--context', 'context:primary-signature', '--verbose=4', disk]);
    manifest.notarization.diskImage.stapled = true;
  }
  await run('/usr/bin/hdiutil', ['verify', disk]);
  await run('/usr/bin/unzip', ['-tq', archive]);
  await writeFile(path.join(output, 'release-notes.md'), await readFile(path.join(repo, 'docs/releases/v' + version + '.md')));
  await writeJson(path.join(output, 'release-check-fixture.json'), [{ draft: false, prerelease: false, tag_name: 'v' + version, html_url: releaseUrl, published_at: new Date().toISOString().replace(/\.\d{3}Z$/, 'Z'), body: 'Local release compatibility fixture; not a published GitHub release.', assets: [{ name: diskName, state: 'uploaded', browser_download_url: 'https://github.com/zero-times/agentupdate/releases/download/v' + version + '/' + diskName }] }]);
  for (const name of [archiveName, diskName, 'source-manifest.json', 'release-notes.md', 'release-check-fixture.json']) {
    const file = path.join(output, name);
    manifest.artifacts.push({ name, bytes: (await stat(file)).size, sha256: digest(await readFile(file)) });
  }
  await writeFile(path.join(output, 'SHA256SUMS'), manifest.artifacts.map(item => item.sha256 + '  ' + item.name).join('\n') + '\n');
  manifest.status = candidate ? 'candidate-built' : 'signed-built';
  manifest.blockers.push('Clean macOS 15 and physical Intel installation, two-tool roundtrip and uninstall acceptance remain pending.');
} catch (error) {
  manifest.status = 'failed';
  manifest.error = error.message;
  throw error;
} finally {
  await writeJson(path.join(output, 'release-manifest.json'), manifest);
  await rm(staging, { recursive: true, force: true });
  console.log(JSON.stringify({ output, status: manifest.status, blockers: manifest.blockers }, null, 2));
}
