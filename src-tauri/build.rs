fn main() {
    // Remove retired command permissions even when reusing an older build directory.
    for name in [
        "rollback_cli_install",
        "rollback_app_install",
        "preview_rollback",
        "rollback_update",
        "get_restore_details",
        "cleanup_restore",
    ] {
        let path = std::path::Path::new("permissions/autogenerated").join(format!("{name}.toml"));
        match std::fs::remove_file(path) {
            Ok(()) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => panic!("Could not remove retired command permission: {error}"),
        }
    }
    // Tauri keeps generated permission files between feature builds. A production
    // build must discard developer-only declarations left by a validation build.
    if std::env::var_os("CARGO_FEATURE_DESKTOP_VALIDATION").is_none() {
        for name in [
            "restricted_probe",
            "probe_panel",
            "finish_panel_validation",
            "finish_cli_launch_validation",
            "finish_desktop_validation",
            "finish_workflow_validation",
        ] {
            let path =
                std::path::Path::new("permissions/autogenerated").join(format!("{name}.toml"));
            match std::fs::remove_file(path) {
                Ok(()) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
                Err(error) => panic!("Could not remove stale validation permission: {error}"),
            }
        }
    }
    let commands: &'static [&'static str] =
        if std::env::var_os("CARGO_FEATURE_DESKTOP_VALIDATION").is_some() {
            &[
                "get_app_overview",
                "hide_main_window",
                "check_app_release",
                "check_desktop_apps",
                "get_cli_projects",
                "save_cli_project",
                "open_cli",
                "install_cli",
                "cli_install_history",
                "prepare_app_install",
                "install_app",
                "app_install_history",
                "finish_app_install",
                "open_desktop_app_channel",
                "open_app_release",
                "get_agent_support",
                "discover_agents",
                "list_agent_versions",
                "select_agent_version",
                "create_update_plan",
                "get_plan_history",
                "export_transaction",
                "reveal_export",
                "inspect_interrupted_tasks",
                "execute_update",
                "execute_plan",
                "cancel_plan",
                "restricted_probe",
                "probe_panel",
                "finish_panel_validation",
                "finish_cli_launch_validation",
                "finish_desktop_validation",
                "finish_workflow_validation",
            ]
        } else {
            &[
                "get_app_overview",
                "hide_main_window",
                "check_app_release",
                "check_desktop_apps",
                "get_cli_projects",
                "save_cli_project",
                "open_cli",
                "install_cli",
                "cli_install_history",
                "prepare_app_install",
                "install_app",
                "app_install_history",
                "finish_app_install",
                "open_desktop_app_channel",
                "open_app_release",
                "get_agent_support",
                "discover_agents",
                "list_agent_versions",
                "select_agent_version",
                "create_update_plan",
                "get_plan_history",
                "export_transaction",
                "reveal_export",
                "inspect_interrupted_tasks",
                "execute_update",
                "execute_plan",
                "cancel_plan",
            ]
        };
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands)),
    )
    .expect("Could not generate application command permissions");
}
